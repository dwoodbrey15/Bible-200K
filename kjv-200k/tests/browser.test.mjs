import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {Transformer,trainStep,generate} from '../model.mjs';
import {packCheckpoint,unpackWeights,unpackOptimizer} from '../checkpoint.mjs';
const require=createRequire(import.meta.url),tf=require('../vendor/tf.min.js');
await tf.setBackend('cpu');await tf.ready();

let model=new Transformer(tf);
assert.equal(model.parameterCount,205376);
const x=tf.tensor2d([[73,110,32,116,104,101,32,98]],undefined,'int32');
const y=tf.tensor2d([[110,32,116,104,101,32,98,101]],undefined,'int32');
let optimizer=tf.train.adam(.001,.9,.95,1e-8);
const firstLoss=model.loss(x,y),before=(await firstLoss.data())[0];firstLoss.dispose();
for(let i=0;i<3;i++) await trainStep(tf,model,optimizer,x,y,.001);
const lastLoss=model.loss(x,y),after=(await lastLoss.data())[0];lastLoss.dispose();
assert(after<before,`loss must fall: ${before} → ${after}`);
console.log(`Full model: ${model.parameterCount} parameters; loss ${before.toFixed(4)} → ${after.toFixed(4)}`);

const checkpoint=await packCheckpoint(tf,model,optimizer,{steps:3});
await trainStep(tf,model,optimizer,x,y,.001);
const expected=await Promise.all(model.variables.map(async v=>Array.from(await v.data())));
model.dispose();optimizer.dispose();
model=new Transformer(tf);optimizer=tf.train.adam(.001,.9,.95,1e-8);
unpackWeights(tf,model,checkpoint);await unpackOptimizer(tf,optimizer,checkpoint);
await trainStep(tf,model,optimizer,x,y,.001);
for(let i=0;i<model.variables.length;i++){
  const actual=await model.variables[i].data();
  for(let j=0;j<actual.length;j++)assert(Math.abs(actual[j]-expected[i][j])<1e-6,'optimizer resume must reproduce the next step');
}
console.log('Checkpoint resumes model and optimizer exactly within 1e-6.');
const startTensors=tf.memory().numTensors;
for(let i=0;i<4;i++)await trainStep(tf,model,optimizer,x,y,.001);
assert(tf.memory().numTensors<=startTensors+1,'training tensors should not leak');
const a=tf.tensor2d([[1,2,3,4,5,6]],undefined,'int32'), b=tf.tensor2d([[1,2,3,40,50,60]],undefined,'int32');
const prefixA=tf.tidy(()=>model.forward(a).slice([0,0,0],[1,3,256])),prefixB=tf.tidy(()=>model.forward(b).slice([0,0,0],[1,3,256]));
const maxDiff=tf.tidy(()=>prefixA.sub(prefixB).abs().max());
assert((await maxDiff.data())[0]<1e-5,'future bytes must not affect earlier logits');
tf.dispose([a,b,prefixA,prefixB,maxDiff]);
const output=await generate(tf,model,'In',3,8);
assert(output.startsWith('In'));
tf.dispose([x,y]);model.dispose();optimizer.dispose();

// Optional cross-framework numerical parity fixture, generated by tests/parity.py.
if(process.argv[2]){
  const fixture=JSON.parse(await readFile(process.argv[2],'utf8'));
  model=new Transformer(tf,fixture.checkpoint.config);unpackWeights(tf,model,fixture.checkpoint);
  const ids=tf.tensor2d(fixture.ids,undefined,'int32'), logits=model.forward(ids);
  const actual=await logits.data();
  let diff=0;for(let i=0;i<actual.length;i++)diff=Math.max(diff,Math.abs(actual[i]-fixture.logits[i]));
  assert(diff<2e-4,`PyTorch/TF.js logits differ: ${diff}`);console.log(`PyTorch/TF.js maximum logit difference: ${diff}`);
  tf.dispose([ids,logits]);model.dispose();
}
assert.equal(tf.memory().numTensors,0,'all tensors must be disposed');
console.log('Browser engine tests passed: causality, learning, checkpoint resume, memory, generation.');
